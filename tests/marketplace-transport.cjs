const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const base = process.env.BASE_URL || 'http://127.0.0.1:4175';

(async () => {
  const { transportCost, osmDirections, transportPlaces, inBangladesh } = await import('../public/marketplace/transport.mjs');
  const input = { quantityKg: 2000, priceKg: 27, acceptedPercent: 95, fare: 8000, handling: 2000, other: 0, partnerKg: 0, capacityKg: '', payer: 'farmer' };
  assert.equal(transportCost(input).net, 41300);
  assert.equal(transportCost({ ...input, partnerKg: 2000 }).net, 45300);
  assert.equal(transportCost({ ...input, partnerKg: 2000 }).savings, 4000);
  assert.equal(transportCost({ ...input, partnerKg: 2000, capacityKg: 3500 }).overloaded, true);
  assert.equal(transportCost({ ...input, payer: 'buyer', fare: '' }).net, 49300);
  for (const change of [{ fare: '' }, { quantityKg: 0 }, { fare: Infinity }, { acceptedPercent: 101 }, { partnerKg: -1 }, { capacityKg: -1 }, { other: NaN }, { payer: 'random' }]) assert.equal(transportCost({ ...input, ...change }), null);
  assert.equal(inBangladesh({ lat: 'script', lon: 90 }), false);
  assert.equal(osmDirections({ lat: 0, lon: 0 }, transportPlaces.Dhaka), '');
  assert.match(osmDirections(transportPlaces.Rangpur, transportPlaces.Dhaka), /^https:\/\/www\.openstreetmap\.org\/directions\?/);

  const browser = await chromium.launch({ headless: true });
  await fs.mkdir('test-results/transport', { recursive: true });
  try {
    for (const [width, language] of [[320, 'bn'], [390, 'en'], [1440, 'en']]) {
      const context = await browser.newContext({ viewport: { width, height: 900 } });
      await context.addInitScript(lang => {
        localStorage.setItem('alusathi-lang', lang);
        sessionStorage.setItem('alusathi-market-demo-farmer', 'Rahim');
        window.__shares = [];
        Object.defineProperty(navigator, 'share', { configurable: true, value: async payload => window.__shares.push(payload) });
      }, language);
      const page = await context.newPage();
      const errors = [];
      let requests = 0;
      page.on('pageerror', error => errors.push(error.message));
      await page.route('https://unpkg.com/**', route => route.abort());
      await page.route('https://router.project-osrm.org/**', route => {
        requests++;
        return route.fulfill({ json: { code: 'Ok', routes: [{ distance: 85000, geometry: { type: 'LineString', coordinates: [[89.2752, 25.7439], [88.6354, 25.6217]] } }] } });
      });
      await page.goto(`${base}/marketplace/farmer.html`);
      await page.locator('[data-action=select-lot]').first().click();
      await page.locator('[data-action=plan-transport][data-id=sample-remote]').click();
      const form = page.locator('#transport-plan');
      await form.waitFor();
      assert.equal(requests, 0, 'No external route request before an explicit click');
      assert.equal(await form.locator('[name=to]').inputValue(), 'Dinajpur');
      assert.equal(await form.locator('[name=fare]').inputValue(), '', 'Do not reuse a sample fare as a real quote');
      assert.equal(await form.locator('[data-transport=save]').isDisabled(), true, 'A quote cannot be saved before a real fare is entered');
      await form.locator('[data-transport=share]').click();
      assert.match(await page.evaluate(() => window.__shares.at(-1).text), language === 'bn' ? /এখনো জানা নেই/ : /Not known yet/);
      await page.locator('.transport-details').first().locator('summary').click();
      await form.locator('[name=capacityKg]').fill('1000');
      const shareCount = await page.evaluate(() => window.__shares.length);
      await form.locator('[data-transport=share]').click();
      assert.equal(await page.evaluate(() => window.__shares.length), shareCount, 'Unknown fare does not bypass the vehicle capacity check');
      await form.locator('[name=capacityKg]').fill('');
      await page.locator('.transport-details').first().locator('summary').click();
      await form.locator('[name=fare]').fill('8000');
      await form.locator('[name=handling]').fill('2000');
      assert.match(await page.locator('.transport-net').innerText(), language === 'bn' ? /৪১,৩০০/ : /41,300/);
      await page.locator('.transport-details').first().locator('summary').click();
      await form.locator('[name=partnerKg]').fill('2000');
      await form.locator('[name=capacityKg]').fill('3500');
      assert.equal(await form.locator('[data-transport=save]').isDisabled(), true);
      await form.locator('[name=capacityKg]').fill('4000');
      assert.match(await page.locator('.transport-net').innerText(), language === 'bn' ? /৪৫,৩০০/ : /45,300/);
      const hostile = '<img src=x onerror="window.__xss=1">';
      await form.locator('[name=operator]').fill(hostile);
      await form.locator('[name=phone]').fill('01712345678');
      await form.locator('[name=checked]').check();
      await form.locator('[data-transport=save]').click();
      assert.equal(await page.locator('.transport-quote').count(), 1);
      assert.equal(await page.locator('.transport-quote img').count(), 0);
      assert.equal(await page.evaluate(() => window.__xss), undefined);
      assert.equal(await page.locator('.transport-quote [href="tel:01712345678"]').count(), 1);
      assert.match(await page.locator('.transport-quote').innerText(), language === 'bn' ? /অন্যের আলু/ : /Other farmers' load/);
      await form.locator('[data-transport=share]').click();
      const shared = await page.evaluate(() => window.__shares.at(-1).text);
      assert.match(shared, language === 'bn' ? /বুকিং নয়/ : /NOT a booking/);
      assert.match(shared, /openstreetmap.org\/directions/);
      assert(!shared.includes('01712345678'), 'Phone is not shared by default');
      await page.screenshot({ path: `test-results/transport/costs-${width}-${language}.png`, fullPage: true });
      await form.locator('[data-transport=route]').click();
      await page.locator('.transport-distance').waitFor();
      assert.equal(requests, 1);
      assert.match(await page.locator('.transport-distance').innerText(), language === 'bn' ? /৮৫/ : /85/);
      await page.locator('[data-transport=route]').click();
      assert.equal(requests, 1, 'Repeated route uses the memory cache');
      await page.locator('[name=to]').selectOption('Dhaka');
      assert.equal(await page.locator('.transport-distance').count(), 0, 'Changing a point invalidates the old distance');
      assert.equal(await page.locator('.transport-quote').count(), 0, 'Do not compare quotes for different routes');
      await page.locator('[name=to]').selectOption('Dinajpur');
      assert.equal(await page.locator('.transport-quote').count(), 1);
      await page.locator('.transport-quote [data-load-quote]').click();
      assert.match(await page.locator('.transport-net').innerText(), language === 'bn' ? /৪৫,৩০০/ : /45,300/);
      await page.locator('[data-action=language]').click();
      assert.equal(await page.locator('[name=fare]').inputValue(), '8000');
      assert.match(await page.locator('.transport-heading').innerText(), language === 'bn' ? /Know the cost/ : /গাড়ির খরচ/);
      await page.locator('[data-action=language]').click();
      await page.reload();
      await page.locator('[data-view=home]:visible').first().click();
      await page.locator('[data-action=select-lot]').first().click();
      await page.locator('[data-action=plan-transport][data-id=sample-remote]').click();
      assert.equal(await page.locator('.transport-quote').count(), 1, 'Saved quote survives reload');
      await page.locator('.transport-quote [data-load-quote]').click();
      await page.locator('[name=operator]').fill('Second operator');
      await page.locator('[name=fare]').fill('6000');
      await page.locator('[data-transport=save]').click();
      assert.equal(await page.locator('.transport-quote').count(), 2);
      assert.match(await page.locator('.transport-quote').first().innerText(), /Second operator/);
      await page.locator('.transport-quote [data-delete-quote]').first().click();
      assert.equal(await page.locator('.transport-quote').count(), 1);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      assert.deepEqual(errors, []);
      await context.close();
    }
    const context = await browser.newContext();
    await context.addInitScript(() => { localStorage.setItem('alusathi-lang', 'en'); sessionStorage.setItem('alusathi-market-demo-farmer', 'Rahim'); });
    const page = await context.newPage();
    await page.route('https://router.project-osrm.org/**', route => route.abort());
    await page.goto(`${base}/marketplace/farmer.html`);
    await page.locator('[data-view=transport]:visible').first().click();
    await page.locator('[data-transport=route]').click();
    await page.getByText(/Route unavailable\. Try later/).waitFor();
    assert.equal(await page.locator('.transport-distance').count(), 0);
    await page.locator('[name=fare]').fill('3000');
    await page.locator('[name=priceKg]').fill('25');
    assert.match(await page.locator('.transport-net').innerText(), /47,000/);
    await context.close();
    if (process.env.LIVE_ROUTE === '1') {
      const live = await browser.newContext({ viewport: { width: 390, height: 900 } });
      await live.addInitScript(() => { localStorage.setItem('alusathi-lang', 'bn'); sessionStorage.setItem('alusathi-market-demo-farmer', 'Rahim'); });
      const page = await live.newPage();
      await page.goto(`${base}/marketplace/farmer.html#transport`);
      await page.locator('#transport-plan').waitFor();
      await page.locator('[data-transport=route]').click();
      await page.locator('.transport-distance').waitFor({ timeout: 20000 });
      await page.locator('.leaflet-container').waitFor({ timeout: 20000 });
      await page.waitForFunction(() => document.querySelectorAll('.leaflet-tile-loaded').length > 0, {}, { timeout: 20000 });
      assert.equal(await page.locator('.leaflet-overlay-pane path').count() > 0, true);
      assert.equal(await page.locator('.leaflet-control-attribution a[href="https://www.openstreetmap.org/copyright"]').count(), 1);
      await page.locator('#transport-map').scrollIntoViewIfNeeded();
      await page.screenshot({ path: 'test-results/transport/live-map-mobile.png' });
      await page.locator('[data-pin=from]').click();
      await page.locator('#transport-map').click({ position: { x: 150, y: 150 } });
      assert.equal(await page.locator('.transport-distance').count(), 0);
      assert.match(await page.locator('.transport-points').innerText(), /তোলার জায়গা আলাদা/);
      console.log('Live OSRM Bangladesh route, real Leaflet map/route overlay, attribution and pickup pin change passed.');
      await live.close();
    }
    console.log('Transport passed: calculations, load capacity, quote CRUD/sorting/persistence, EN/BN, sharing, XSS, route cache/invalidation/failure and 320/390/1440px layouts. Route API mocked; live route/map checked separately.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
