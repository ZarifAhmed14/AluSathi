const {chromium} = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const users = JSON.parse(fs.readFileSync('test-results/auth-fixtures.json','utf8'));
const env = Object.fromEntries(fs.readFileSync('.env','utf8').trim().split(/\r?\n/).map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1).replace(/^"|"$/g,'')];}));
const BASE='http://127.0.0.1:4173';
(async()=>{
  const browser=await chromium.launch({headless:true});
  const errors=[];
  const context=await browser.newContext({viewport:{width:390,height:844}});
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(BASE,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Change language'}).click();
  await page.getByRole('link',{name:'Log in',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill(users[0].email);
  await page.getByLabel('Password',{exact:true}).fill(users[0].password);
  await page.getByRole('button',{name:'Log in',exact:true}).click();
  await page.getByRole('button',{name:'Sign out',exact:true}).waitFor({timeout:25000});
  const cookies=await context.cookies();
  assert(cookies.some(c=>c.name==='alusathi_refresh' && c.httpOnly && c.sameSite==='Strict'));
  assert(!(await page.evaluate(()=>Object.keys(localStorage))).some(k=>k.includes('auth-token')));
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Sign out',exact:true}).waitFor({timeout:25000});
  await page.locator('.reminder-tool > summary').click();
  await page.getByLabel('What task?').fill('QA follow-up photo');
  await page.getByLabel('When?').fill(new Date(Date.now()+3600000-new Date().getTimezoneOffset()*60000).toISOString().slice(0,16));
  await page.getByRole('button',{name:'Save reminder',exact:true}).click();
  await page.locator('.reminder-list strong').filter({hasText:'QA follow-up photo'}).waitFor();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Add to calendar',exact:true}).click();
  assert((await download).suggestedFilename().endsWith('.ics'));
  await page.screenshot({path:'test-results/reminders-mobile.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const auth = async (user) => {
    const response=await context.request.post(BASE+'/api/auth/signin',{headers:{Origin:BASE,'X-AluSathi-Request':'1'},data:{email:user.email,password:user.password}});
    assert.equal(response.status(),200,'Live sign-in failed'); return response.json();
  };
  const a=await auth(users[0]); const b=await auth(users[1]);
  const rest=async(token,path,method='GET',data)=>{
    const res=await fetch(env.VITE_SUPABASE_URL+'/rest/v1/'+path,{method,headers:{apikey:env.VITE_SUPABASE_PUBLISHABLE_KEY,Authorization:'Bearer '+token,'Content-Type':'application/json',Prefer:'return=representation'},body:data?JSON.stringify(data):undefined});
    return {status:res.status,data:await res.json().catch(()=>null)};
  };
  const own=await rest(a.access_token,'treatment_reminders?select=*');
  assert.equal(own.status,200); const record=own.data.find(r=>r.title==='QA follow-up photo'); assert(record);
  const other=await rest(b.access_token,'treatment_reminders?select=*'); assert.deepEqual(other.data,[]);
  const stolen=await rest(b.access_token,'treatment_reminders','POST',{user_id:users[0].id,title:'forbidden',due_at:new Date().toISOString()}); assert(stolen.status>=400);
  const changed=await rest(b.access_token,'treatment_reminders?id=eq.'+record.id,'PATCH',{completed:true}); assert.deepEqual(changed.data,[]);
  assert((await rest(a.access_token,'rpc/push_worker_config','POST',{})).status>=400);
  assert((await rest(a.access_token,'treatment_reminders?id=eq.'+record.id,'PATCH',{notified_at:new Date().toISOString()})).status>=400);
  await auth(users[0]); await page.reload({waitUntil:'networkidle'});
  await page.locator('.reminder-tool > summary').click();
  await page.getByRole('button',{name:'Mark complete',exact:true}).click();
  await page.getByText('Completed',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Delete reminder',exact:true}).click();
  await page.getByText('No reminders yet.').waitFor();
  const denied=await context.request.post(BASE+'/api/auth/signin',{headers:{Origin:'https://evil.example','X-AluSathi-Request':'1'},data:{}}); assert.equal(denied.status(),403);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByRole('link',{name:'Log in',exact:true}).waitFor();
  assert(!(await context.cookies()).some(c=>c.name==='alusathi_refresh'));
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.getByRole('button',{name:'Sign out',exact:true}).count(),0);
  await context.close(); await browser.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: live login, protected cookie, reload, signout, reminders, calendar, mobile layout, cross-account RLS and CSRF.');
})().catch(e=>{console.error(e);process.exit(1)});
